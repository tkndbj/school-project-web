"use client";

import type { Route } from "next";
import { useRouter } from "next/navigation";
import { useTranslations } from "next-intl";
import { useEffect, useState } from "react";
import { Alert, AlertDescription } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Field, FieldDescription, FieldGroup, FieldLabel } from "@/components/ui/field";
import { Input } from "@/components/ui/input";
import { Skeleton } from "@/components/ui/skeleton";
import { Spinner } from "@/components/ui/spinner";
import { getBrowserSupabase } from "@/lib/supabase/client";

type Stage =
  | { kind: "loading" }
  | { kind: "enroll"; factorId: string; qrCode: string; secret: string }
  | { kind: "verify"; factorId: string }
  | { kind: "error" };

/**
 * Time-based one-time password (authenticator app) step. Enrolls a factor on
 * first use, otherwise verifies the existing one, raising the session to AAL2.
 */
export function MfaForm({ next }: { next: string }) {
  const t = useTranslations("auth");
  const router = useRouter();
  const [stage, setStage] = useState<Stage>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    const supabase = getBrowserSupabase();
    let cancelled = false;

    (async () => {
      const { data, error: listError } = await supabase.auth.mfa.listFactors();
      if (cancelled) return;
      if (listError) return setStage({ kind: "error" });

      const verified = data.totp[0];
      if (verified) return setStage({ kind: "verify", factorId: verified.id });

      // Remove abandoned, never-verified enrolments before starting a new one.
      for (const factor of data.all.filter((f) => f.factor_type === "totp" && f.status === "unverified")) {
        await supabase.auth.mfa.unenroll({ factorId: factor.id });
      }
      const { data: enrolled, error: enrollError } = await supabase.auth.mfa.enroll({
        factorType: "totp",
        friendlyName: `Authenticator ${new Date().toISOString().slice(0, 10)}`,
      });
      if (cancelled) return;
      if (enrollError || !enrolled) return setStage({ kind: "error" });
      setStage({
        kind: "enroll",
        factorId: enrolled.id,
        qrCode: enrolled.totp.qr_code,
        secret: enrolled.totp.secret,
      });
    })();

    return () => {
      cancelled = true;
    };
  }, []);

  async function onSubmit(event: React.FormEvent) {
    event.preventDefault();
    if (stage.kind !== "enroll" && stage.kind !== "verify") return;
    setPending(true);
    setError(null);
    const { error: verifyError } = await getBrowserSupabase().auth.mfa.challengeAndVerify({
      factorId: stage.factorId,
      code: code.replace(/\s/g, ""),
    });
    setPending(false);
    if (verifyError) {
      setError(t("mfaInvalidCode"));
      return;
    }
    router.replace(next as Route);
    router.refresh();
  }

  return (
    <Card>
      <CardHeader>
        <CardTitle className="text-xl">{t("mfaTitle")}</CardTitle>
        <CardDescription>{stage.kind === "enroll" ? t("mfaEnrollDescription") : t("mfaVerifyDescription")}</CardDescription>
      </CardHeader>
      <CardContent>
        {stage.kind === "loading" ? <Skeleton className="h-48 w-full" /> : null}
        {stage.kind === "error" ? (
          <Alert variant="destructive">
            <AlertDescription>{t("mfaUnavailable")}</AlertDescription>
          </Alert>
        ) : null}
        {stage.kind === "enroll" || stage.kind === "verify" ? (
          <form onSubmit={onSubmit}>
            <FieldGroup>
              {stage.kind === "enroll" ? (
                <div className="flex flex-col items-center gap-2">
                  {/* eslint-disable-next-line @next/next/no-img-element -- data: URL generated by Supabase */}
                  <img src={stage.qrCode} alt={t("mfaQrAlt")} className="size-48 rounded-lg bg-white p-2" />
                  <p className="text-center text-xs text-muted-foreground">
                    {t("mfaSecretHint")} <code className="font-mono break-all">{stage.secret}</code>
                  </p>
                </div>
              ) : null}
              {error ? (
                <Alert variant="destructive">
                  <AlertDescription>{error}</AlertDescription>
                </Alert>
              ) : null}
              <Field>
                <FieldLabel htmlFor="code">{t("mfaCode")}</FieldLabel>
                <Input
                  id="code"
                  inputMode="numeric"
                  autoComplete="one-time-code"
                  pattern="[0-9 ]{6,7}"
                  maxLength={7}
                  value={code}
                  onChange={(e) => setCode(e.target.value)}
                  autoFocus
                  required
                />
                <FieldDescription>{t("mfaCodeHint")}</FieldDescription>
              </Field>
              <Button type="submit" size="lg" disabled={pending || code.replace(/\s/g, "").length !== 6}>
                {pending ? <Spinner /> : null}
                {t("mfaVerify")}
              </Button>
            </FieldGroup>
          </form>
        ) : null}
      </CardContent>
    </Card>
  );
}
